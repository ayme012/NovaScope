"""
Step 2: build data/stars.js, everything the star map needs.

Inputs (put them in tools/sources/):
  hygdata_v41.csv               HYG Database v4.1, https://github.com/astronexus/HYG-Database (CC BY-SA 4.0)
  constellations.lines.json     d3-celestial, data/ folder of the npm package "d3-celestial" (BSD)
  constellations.json           d3-celestial, same folder
  milky_way_points.npy          made by milky_way.py

Output: ../data/stars.js  (window.STARLIGHT_DATA = {...})

What goes in:
  - every star brighter than magnitude 7 (plus Barnard's, Kapteyn's and Proxima Centauri):
    position x,y,z (parsecs), velocity vx,vy,vz (parsecs/year), absolute magnitude, colour index.
    The app moves each star in a straight line: position(t) = position + velocity * (t - 2000),
    then recomputes direction and brightness from the new distance.
  - constellation stick figures, snapped to real star indices so the lines move with the stars
  - the Milky Way points
Big number arrays are packed as base64 binary (Float32, Int32, ...) to keep the file small.
"""
import base64
import json
import numpy as np
import pandas as pd

d = pd.read_csv("sources/hygdata_v41.csv", low_memory=False)
d = d[d.id != 0]                                                    # drop the Sun
extra = d.proper.isin(["Barnard's Star", "Kapteyn's Star", "Proxima Centauri"])
s = d[(d.mag <= 7.0) | extra].copy().reset_index(drop=True)
s["ci"] = s.ci.fillna(0.6)
s.loc[s.dist >= 99999, ["vx", "vy", "vz"]] = 0.0                    # HYG uses 100000 pc for "distance unknown"

speed = np.sqrt(s.vx ** 2 + s.vy ** 2 + s.vz ** 2) * 977792.0       # pc/yr -> km/s, sanity check
print("Barnard's Star speed:", round(float(speed[s.proper == "Barnard's Star"].iloc[0]), 1), "km/s (published: ~142)")

stars = s[["x", "y", "z", "vx", "vy", "vz", "absmag", "ci"]].to_numpy(np.float32)
cons = sorted(c for c in s.con.dropna().unique())
con_idx = np.array([cons.index(c) if isinstance(c, str) else 255 for c in s.con], np.uint8)
hip = s.hip.fillna(0).astype(np.int32).to_numpy()
hd = s.hd.fillna(0).astype(np.int32).to_numpy()
names = [[int(i), n] for i, n in zip(s.index, s.proper) if isinstance(n, str)]
bayer = [[int(i), b] for i, b in zip(s.index, s.bayer) if isinstance(b, str) and b]

# Snap each constellation-line vertex to the nearest star brighter than mag 6.5 (within 0.4 degrees)
ra = np.radians(s.ra.to_numpy() * 15)
de = np.radians(s.dec.to_numpy())
U = np.c_[np.cos(de) * np.cos(ra), np.cos(de) * np.sin(ra), np.sin(de)]
bright = (s.mag <= 6.5).to_numpy()
lines = {}
for f in json.load(open("sources/constellations.lines.json"))["features"]:
    segs = []
    for line in f["geometry"]["coordinates"]:
        idx = []
        for lon, lat in line:
            a, b = np.radians(lon % 360), np.radians(lat)
            v = np.array([np.cos(b) * np.cos(a), np.cos(b) * np.sin(a), np.sin(b)])
            dots = U @ v
            dots[~bright] = -2
            j = int(np.argmax(dots))
            idx.append(j if np.degrees(np.arccos(min(1, dots[j]))) <= 0.4 else -1)
        for p, q in zip(idx, idx[1:]):
            if p >= 0 and q >= 0 and p != q:
                segs += [p, q]
    lines[f["id"]] = segs
cname = {f["properties"]["desig"]: f["properties"]["en"] for f in json.load(open("sources/constellations.json"))["features"]}

mw = np.load("milky_way_points.npy")
mw = mw[mw[:, 2] > 0]
mw_q = np.c_[np.round(mw[:, 0] * 100), np.round(mw[:, 1] * 100)].astype(np.int16)

b64 = lambda a: base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()
spect = [x if isinstance(x, str) else "" for x in s.spect]          # spectral type, e.g. "G2V", for the Star tab's facts
out = dict(spect=spect, n=len(s), stars=b64(stars), con=b64(con_idx), hip=b64(hip), hd=b64(hd), cons=cons, cname=cname,
           names=names, bayer=bayer, lines=lines, mw=b64(mw_q), mwl=b64(mw[:, 2].astype(np.uint8)))
with open("../data/stars.js", "w") as f:
    f.write("// Generated by tools/build_stars.py\nwindow.STARLIGHT_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(s), "stars written")
