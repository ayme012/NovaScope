"""
Step 3b: shrink the IRSA tutorial figures and pack them, with the M101 frames, into data/spherex.js.

Inputs (sources/, all from the gh-pages branch of https://github.com/Caltech-IPAC/irsa-tutorials,
_public/ folder, BSD 3-Clause, Caltech):
  lvf.png        cae4d4ee10883fe69a0ef1a138cad45c.png   wavelength across detector 1 (spherex-intro)
  mosaic.png     129ae5fa892b3d71d9a72deea3311404.png   M101 mosaic with apertures   (spherex-mosaic)
  spectrum.png   b63045174cf22bb0cca39c50552d107a.png   M101 spectrum                (spherex-mosaic)
  pah.png        04203b8936167314fc90b300c63e981c.png   M101 3.3 um dust map         (spherex-mosaic)
  galex.png      d996efd030be25c456b5c2b1558cc34a.png   dust over GALEX ultraviolet  (spherex-mosaic)
  hips3.png      f47979af77b602d52162d9b0dc935486.png   science / hits / flags panels (spherex-hipscube)
  hipsap.png     989ecf118276c8dd6b8264122ee8563c.png   cloud with apertures         (spherex-hipscube)
  hipsspec.png   0cc896547d7f04b91ec3fa2d98169549.png   cloud spectrum               (spherex-hipscube)
  m101_frames.json                                       made by extract_m101_frames.py
  atlas.json                                             made by extract_atlas.py
  m101_disc.json                                         made by extract_m101_mosaic.py
Output: ../data/spherex.js  (window.SPHEREX_DATA = {m101: [...], figs: {name: data URI}, atlas: {...}, m101disc: {...}})
"""
import base64
import io
import json
from PIL import Image

def webp(img, width):
    if img.width > width:
        img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    b = io.BytesIO()
    img.save(b, "WEBP", quality=86, method=6)
    return "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode()

figs = {}
for key, width in [("lvf", 640), ("mosaic", 640), ("spectrum", 640), ("pah", 640), ("galex", 640),
                   ("hipsap", 470), ("hipsspec", 700)]:
    figs[key] = webp(Image.open(f"sources/{key}.png").convert("RGB"), width)
three = Image.open("sources/hips3.png").convert("RGB")        # split the 3-panel figure; the flags panel is almost blank
figs["hipssci"] = webp(three.crop((0, 0, 470, three.height)), 470)
figs["hipshits"] = webp(three.crop((490, 0, 980, three.height)), 490)

out = {"m101": json.load(open("m101_frames.json")), "figs": figs, "atlas": json.load(open("atlas.json")),
       "m101disc": json.load(open("m101_disc.json"))}
with open("../data/spherex.js", "w") as f:
    f.write("// Generated by tools/extract_m101_frames.py, extract_atlas.py, extract_m101_mosaic.py and encode_figures.py\nwindow.SPHEREX_DATA = "
            + json.dumps(out, separators=(",", ":")) + ";\n")
print("figures:", ", ".join(figs))
